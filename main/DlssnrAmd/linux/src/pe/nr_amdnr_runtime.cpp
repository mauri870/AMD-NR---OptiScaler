constexpr uint32_t kMaxExtent = 4096;
// Frame-info sizes a host has sent over the ABI's life; anything else is a different struct.
constexpr uint32_t kFrameInfoSizes[] = {64, 88, 120, 128, 144};

std::mutex g_lock;
std::string g_last_error;

int32_t fail(int32_t code, std::string message) {
    g_last_error = std::move(message);
    log("[amdnr] %s", g_last_error.c_str());
    return code;
}

int32_t code_of(Result r) {
    switch (r) {
        case Result::Ok: return NR_ABI_OK;
        case Result::Unavailable: return NR_ABI_UNAVAILABLE;
        default: return NR_ABI_FAILED;
    }
}

struct JobEntry {
    uint32_t state = NR_ABI_JOB_NONE;
    std::unique_ptr<nr::amdnr::Job> job;
};

struct Context {
    std::unique_ptr<nr::amdnr::Transport> transport;
    std::vector<std::unique_ptr<JobEntry>> jobs;
    uint64_t answers = 0;
    bool logged_strength = false, logged_passes = false;
    uint32_t width = 0, height = 0;   // of the last frame
};

Context* as_context(void* p) { return static_cast<Context*>(p); }
JobEntry* find_job(Context* c, void* handle) {
    for (auto& j : c->jobs)
        if (j.get() == handle) return j.get();
    return nullptr;
}

void remove_job(Context& c, JobEntry* entry, bool wait) {
    for (auto it = c.jobs.begin(); it != c.jobs.end(); ++it) {
        if (it->get() != entry) continue;
        if (entry->job) c.transport->finish(std::move(entry->job), wait);
        c.jobs.erase(it);
        return;
    }
}

