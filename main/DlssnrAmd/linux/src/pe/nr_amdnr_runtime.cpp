// DlssnrAmdRuntime.dll: this project's network as a neural runtime for AMDNR's OptiScaler.
//
// AMDNR's host (https://github.com/3zwr1/AMD-NR---OptiScaler, dlssnr/lmxxf/LmxxfBackend.cpp) feeds a
// neural runtime an encoded FP16 proxy of the frame at the network's size (and, for history, a
// motion image), and later takes the network's answer back as an FP16 texture; it forms the edit
// itself (answer minus what the network was fed). That contract is the C ABI in nr_amdnr_abi.hpp,
// exported under the names the host looks up.
//
// This file is the ABI: it checks what the host sends, keeps each job's state, and hands the work to
// a transport (nr_amdnr_transport.hpp) - the network recorded into the host's own command list when
// the D3D12 device is vkd3d-proton, or run on a Vulkan device of our own beside the host's otherwise.

