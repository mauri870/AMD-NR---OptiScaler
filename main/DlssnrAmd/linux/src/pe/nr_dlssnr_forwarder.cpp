__declspec(dllexport) int dlssnr_vk_last_init = 0;
__declspec(dllexport) int dlssnr_vk_last_create = 0;

// The bit field OptiScaler reads to decide whether the native Vulkan path exists at all: init 1,
// create 2, evaluate 4, release 8. Fifteen, because all four are implemented here.
__declspec(dllexport) int dlssnr_vk_probe(const wchar_t* snippetPath) {
    (void) snippetPath;
    return 15;
}

__declspec(dllexport) int dlssnr_vk_init(const wchar_t* snippetPath, const wchar_t* dataPath,
                                         void* instance, void* physicalDevice, void* device,
                                         int sdkVersion) {
    (void) snippetPath;
    (void) dataPath;
    (void) sdkVersion;
    dlssnr_vk_last_init = nr::dlssnr::vk_init(instance, physicalDevice, device);
    return dlssnr_vk_last_init;
}

__declspec(dllexport) void* dlssnr_vk_create(void* cmdBuffer, void* capabilityParams, unsigned int width,
                                             unsigned int height, int preset, float intensity, int style,
                                             float localStructure, float localTone, float skinStructure,
                                             int useAutoMask, int uiCorrection) {
    return nr::dlssnr::create_vk(cmdBuffer, capabilityParams, width, height, preset, uiCorrection,
                                 controls6(intensity, style, localStructure, localTone, skinStructure,
                                           useAutoMask),
                                 &dlssnr_vk_last_create);
}

// Colour and output are at the working resolution; depth and motion come from the game's own upscaler
// call and may be at a different one, so each carries its own subrect and the caller has already
// scaled the motion vectors by the working/active ratio (DlssNr_Dx12.cpp: mvToWorkX = workWidth/width,
// passed as guideMvScaleX * mvToWorkX). The reference forwarder does not compute that ratio itself --
// it hands the number straight to DLSSNR.MVecScaleX -- and neither does this one.
__declspec(dllexport) int dlssnr_vk_evaluate_v2(void* cmdBuffer, void* feature, void* capabilityParams,
                                             void* color, void* depth, void* motion, void* output,
                                             unsigned int width, unsigned int height,
                                             unsigned int guideWidth, unsigned int guideHeight,
                                             unsigned int motionWidth, unsigned int motionHeight,
                                             unsigned int depthBaseX, unsigned int depthBaseY,
                                             unsigned int motionBaseX, unsigned int motionBaseY,
                                             int depthInverted, int reset, float intensity, int style,
                                             float localStructure, float localTone, float skinStructure,
                                             int useAutoMask, float mvScaleX, float mvScaleY) {
    const nr::dlssnr::Rect depth_rect{depthBaseX, depthBaseY, guideWidth, guideHeight};
    const nr::dlssnr::Rect motion_rect{motionBaseX, motionBaseY, motionWidth, motionHeight};
    return nr::dlssnr::evaluate_vk(cmdBuffer, as_feature(feature), capabilityParams, color, depth,
                                   motion, output, width, height, depth_rect, motion_rect,
                                   depthInverted, reset,
                                   controls6(intensity, style, localStructure, localTone,
                                             skinStructure, useAutoMask),
                                   mvScaleX, mvScaleY);
}

// The v1 evaluate, kept for a host built against the older ABI. v1 carried one guide extent and no
// origins, and its guideWidth/Height applied to depth and motion alike -- which is what passing them
// twice here says.
__declspec(dllexport) int dlssnr_vk_evaluate(void* cmdBuffer, void* feature, void* capabilityParams,
                                             void* color, void* depth, void* motion, void* output,
                                             unsigned int width, unsigned int height,
                                             unsigned int guideWidth, unsigned int guideHeight,
                                             int depthInverted, int reset, float intensity, int style,
                                             float localStructure, float localTone, float skinStructure,
                                             int useAutoMask, float mvScaleX, float mvScaleY) {
    return dlssnr_vk_evaluate_v2(cmdBuffer, feature, capabilityParams, color, depth, motion, output,
                                 width, height, guideWidth, guideHeight, guideWidth, guideHeight,
                                 0, 0, 0, 0, depthInverted, reset, intensity, style, localStructure,
                                 localTone, skinStructure, useAutoMask, mvScaleX, mvScaleY);
}

__declspec(dllexport) void dlssnr_vk_release(void* feature) { nr::dlssnr::release_vk(as_feature(feature)); }

