// The extras NVIDIA's Streamline plugin sets and the positional exports predate.
//
// globalTone is inert. It is inert in the reference too -- DLSSNR.GlobalToneStrength is not one of the
// snippet's 61 DLSSNR.* names (the pre-SR fork's own DlssNr_Common.h:315-320 says so and leaves the
// constant commented out), so every write went into a map nothing read -- and it is inert here for
// the stronger reason that our network has no such control: nr::Controls carries local_tone, which is
// a different thing and arrives through evaluate. Kept in the signature so the ABI does not churn.
//
// The UI layer, its alpha and the back buffer are accepted and dropped. Our network has no UI
// correction pass, so there is nothing to give them to; OptiScaler always passes nulls here anyway
