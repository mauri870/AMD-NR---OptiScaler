// nvngx.dll_dlssnr.dll for AMD: the exports OptiScaler's DLSS-NR forks drive the model through,
// backed by our own network instead of NVIDIA's snippet.
//
// 28 of them: the 25 Dagherbou's OptiScaler_DLSSNR publishes, plus the three the pre-SR fork added --
// dlssnr_call_evaluate_v2, dlssnr_vk_evaluate_v2 (per-resource subrects, so depth and motion may be at
// a different resolution from colour) and dlssnr_call_error (why the model declined, in words). The
// fork resolves ONLY the v2 names and refuses to run without them; the v1 pair is kept because there
// are hosts that still drive it.
//
// This file is now only the ABI. The model behind it -- the sessions, the features, the history rule,
// the seed copy and the control mapping -- is linux/src/pe/nr_dlssnr_model.cpp, shared with _nvngx.dll,
// which reaches the same model through NVSDK_NGX_D3D12_CreateFeature(18). wilsjo2's fork from 0.8.1 on
// loads no forwarder at all and uses that door instead; Dagherbou's release uses this one.
//
// OptiScaler is not modified. It loads "nvngx.dll_dlssnr.dll" from beside itself or the executable,
// resolves the exports below by name, and drives them exactly as it drives NVIDIA's. Everything about
// the call sequence, the argument order and the return conventions was read from, and must keep
// matching:
//
//   OptiScaler_DLSSNR/OptiScaler/dlssnr/forwarder/dlssnr_forwarder.cpp   (the ABI)
//   OptiScaler_DLSSNR/OptiScaler/shaders/dlssnr/DlssNr_Dx12.cpp          (the D3D12 caller)
//   OptiScaler_DLSSNR/OptiScaler/dlssnr/DlssNrFeature_Vk.cpp             (the Vulkan caller)
//
// and for the v2 surface:
//
//   artifacts/ref/wilsjo2-OptiScaler-DLSSNR-PreSR-Multipass/OptiScaler/dlssnr/forwarder/dlssnr_forwarder.cpp
//   artifacts/ref/wilsjo2-OptiScaler-DLSSNR-PreSR-Multipass/OptiScaler/shaders/dlssnr/DlssNr_Dx12.cpp
//   artifacts/ref/wilsjo2-OptiScaler-DLSSNR-PreSR-Multipass/OptiScaler/shaders/dlssnr/DlssNr_Guides.h
//
// What the reference forwarder exists for does not apply here and is deliberately absent: it is a
// module whose *path* contains "nvngx.dll", because NVIDIA's snippet resolves its caller's module and
// refuses anyone else. There is no snippet on this side and no caller gate. The file name is kept
// because it is what OptiScaler looks for, not because anything checks it.

