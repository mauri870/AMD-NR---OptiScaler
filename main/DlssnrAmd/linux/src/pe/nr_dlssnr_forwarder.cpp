__declspec(dllexport) void* dlssnr_call_create(const wchar_t* snippetPath, const wchar_t* dataPath,
                                               ID3D12Device* device, ID3D12GraphicsCommandList* cmd,
                                               void* capabilityParams, unsigned int width,
                                               unsigned int height, int preset, float intensity,
                                               int style, float localStructure, float localTone,
                                               float skinStructure, int useAutoMask,
                                               int uiCorrection) {
    (void) snippetPath;
    (void) dataPath;
    void* feature = nr::dlssnr::create_d3d12(device, cmd, capabilityParams, width, height, preset,
                                             uiCorrection,
                                             controls6(intensity, style, localStructure, localTone,
                                                       skinStructure, useAutoMask),
                                             &dlssnr_call_last_create);
    // The reference publishes both numbers and OptiScaler prints both; on this side there is no init
    // step separate from create, so they carry the same answer.
    dlssnr_call_last_init = dlssnr_call_last_create;
    return feature;
}

// Colour and output are at the working resolution; depth and motion come from the game's own upscaler
// call and may be at a different one, so each carries its own subrect base and extent, and the motion
// vectors arrive already scaled by the working/active ratio the caller computed
// (DlssNr_Dx12.cpp: guideMvScaleX * workWidth/width).
__declspec(dllexport) int dlssnr_call_evaluate_v2(ID3D12GraphicsCommandList* cmd, void* feature,
                                               void* capabilityParams, ID3D12Resource* color,
                                               ID3D12Resource* depth, ID3D12Resource* motion,
                                               ID3D12Resource* output, unsigned int width,
                                               unsigned int height, unsigned int guideWidth,
                                               unsigned int guideHeight, unsigned int motionWidth,
                                               unsigned int motionHeight, unsigned int depthBaseX,
                                               unsigned int depthBaseY, unsigned int motionBaseX,
                                               unsigned int motionBaseY, int depthInverted, int reset,
                                               float intensity, int style, float localStructure,
                                               float localTone, float skinStructure, int useAutoMask,
                                               float mvScaleX, float mvScaleY) {
    const nr::dlssnr::Rect depth_rect{depthBaseX, depthBaseY, guideWidth, guideHeight};
    const nr::dlssnr::Rect motion_rect{motionBaseX, motionBaseY, motionWidth, motionHeight};
    return nr::dlssnr::evaluate_d3d12(cmd, as_feature(feature), capabilityParams, color, depth, motion,
                                      output, width, height, depth_rect, motion_rect, depthInverted,
                                      reset,
                                      controls6(intensity, style, localStructure, localTone,
                                                skinStructure, useAutoMask),
                                      mvScaleX, mvScaleY);
}

